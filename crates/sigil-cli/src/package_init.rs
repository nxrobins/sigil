fn hash(bytes: &[u8]) -> String {
    let hex: String = digest(&SHA256, bytes)
        .as_ref()
        .iter()
        .map(|byte| format!("{byte:02x}"))
        .collect();
    format!("sha256:{hex}")
}

fn json_bytes(value: &Value) -> anyhow::Result<Vec<u8>> {
    let mut bytes = serde_json::to_vec_pretty(value)?;
    bytes.push(b'\n');
    Ok(bytes)
}

fn create_file(root: &Path, name: &str, bytes: &[u8]) -> anyhow::Result<()> {
    // Only creator-owned fresh files are written; partial failure stays visible
    // and closed, without recursive deletion of caller-owned destinations.
    let path = root.join(name);
    let mut file = OpenOptions::new()
        .write(true)
        .create_new(true)
        .open(&path)
        .with_context(|| format!("create starter file `{}`", path.display()))?;
    file.write_all(bytes)?;
    Ok(())
}

pub(crate) fn run(
    root: &Path,
    namespace: &str,
    dependencies: &[LocalPackageDependency],
    fmt: OutputFormat,
) -> anyhow::Result<()> {
    crate::package_artifacts::emit("package-init", fmt, create(root, namespace, dependencies))
}

fn create(
    root: &Path,
    namespace: &str,
    dependencies: &[LocalPackageDependency],
) -> anyhow::Result<Value> {
    if !(2..=64).contains(&namespace.len())
        || !namespace.as_bytes()[0].is_ascii_lowercase()
        || !namespace
            .bytes()
            .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || b"_-".contains(&c))
    {
        bail!(
            "--namespace must be 2..64 lowercase ASCII letters, digits, _ or -, starting with a letter"
        );
    }
    if dependencies.len() != 2 {
        bail!("package-init requires exactly sigil/bytes and sigil/fmt via --dependency");
    }
    let parent = root
        .parent()
        .filter(|path| !path.as_os_str().is_empty())
        .unwrap_or(Path::new("."));
    let parent = parent
        .canonicalize()
        .context("starter parent must already exist")?;
    let leaf = root
        .file_name()
        .context("--root must name a new project directory")?;
    let target = parent.join(leaf);
    let mut selected = Vec::new();
    let mut declarations = Vec::new();
    for package in ["sigil/bytes", "sigil/fmt"] {
        let dependency = dependencies
            .iter()
            .find(|dep| dep.package == package)
            .with_context(|| format!("missing --dependency {package}=DIR"))?;
        // Derivation is read-only: do not trust a stale provider lock or borrow
        // its hashes from another consumer. The normal loader rejects unsafe
        // sources, unsupported features and malformed manifests again at lock.
        let lock: Value = serde_json::from_slice(&derive_local_package_lock(&dependency.path)?)?;
        let node = &lock["nodes"][0];
        if node["package"] != package || node["features"] != json!([]) {
            bail!("selected source must be feature-free {package}");
        }
        let source = dependency.path.canonicalize()?;
        if target.starts_with(&source) || source.starts_with(&target) {
            bail!("starter and selected package directories must be disjoint");
        }
        declarations.push(json!({
            "package": package, "requirement": format!("={}", node["version"].as_str().context("derived version")?),
            "source": "workspace", "content_hash": node["content_hash"],
            "optional": false, "default_features": false, "features": []
        }));
        selected.push(LocalPackageDependency {
            package: package.to_owned(),
            path: source,
        });
    }
    let card = json_bytes(&json!({
        "package": format!("{namespace}/tool"), "version": "0.1.0-dogfood.1",
        "status": "experimental_private_unreviewed_not_admitted", "entry": "tool::tool_main",
        "parameters": ["input_ptr:i64@Public", "input_len:i64@Public"], "result": "i64@Public",
        "effects": ["Alloc"], "host_imports": [], "dependencies": ["sigil/bytes", "sigil/fmt"]
    }))?;
    let inventory = json_bytes(&json!({
        "scope": "initial private scaffold only; not an admission evidence manifest",
        "files": {"src/tool.sigil": hash(SOURCE.as_bytes()), "API.md": hash(API.as_bytes()),
                  "README.md": hash(README.as_bytes()), "api-card.json": hash(&card)}
    }))?;
    let manifest = json_bytes(&json!({
        "format_version": "1", "namespace": namespace, "name": "tool", "version": "0.1.0-dogfood.1",
        "maturity": "contracted", "description": "Experimental private bytes/fmt starter; unreviewed and not admitted.",
        "license": "MIT OR Apache-2.0", "compiler": {"requires": format!("={COMPILER_VERSION}"), "features": []},
        "modules": ["tool"], "dependencies": declarations, "features": {"default": [], "available": {}},
        "declared": {"rings": ["inner"], "effects": ["Alloc"], "host_imports": [], "grant_categories": [],
            "trusted_surface": [], "stable_errors": [], "trap_conditions": [], "determinism": "state_relative",
            "resource_contract_ref": "API.md", "taint_contracts": ["tool::tool_main(input_ptr:Public,input_len:Public)->Public"]},
        "evidence": {"charter_hash": hash(README.as_bytes()), "api_contract_hash": hash(API.as_bytes()),
            "api_card_hash": hash(&card), "evidence_manifest_hash": hash(&inventory)}
    }))?;
    fs::create_dir(&target)
        .with_context(|| format!("create NEW starter directory `{}`", target.display()))?;
    fs::create_dir(target.join("src"))?;
    for (name, bytes) in [
        ("src/tool.sigil", SOURCE.as_bytes()),
        ("API.md", API.as_bytes()),
        ("README.md", README.as_bytes()),
        ("api-card.json", &card),
        ("starter-inputs.json", &inventory),
        ("sigil-package.json", &manifest),
        (".gitignore", b"/.sigil/\n".as_slice()),
    ] {
        create_file(&target, name, bytes)?;
    }
    let lock = create_local_package_lock_with_dependencies(&target, &selected)?;
    Ok(
        json!({"root": target, "root_package": format!("{namespace}/tool"),
        "template": "bytes-fmt", "locked": true, "lock_bytes": lock.len(), "admission": "not_evaluated"}),
    )
}
